const WIDTHS = new Map<string, number>();
for (const [width, chars] of WIDTH_GROUPS) {
  for (const char of chars) WIDTHS.set(char, width);
}

// Незнакомый символ (эмодзи, редкая пунктуация) считаем по ширине цифры —
// она же средняя по таблице. Ошибка на один символ погоды не делает, а
// падать на неизвестном глифе этой функции незачем.
const FALLBACK_WIDTH = 556;

// Замер десктопной выдачи: обрезка наступает около 600px. Совпадения до
// пикселя тут быть не может (у Google свой рендер и свой шрифт), поэтому
// значение стоит ровно на пороге, а заголовки собираются с запасом — см.
// список вариантов в fallbackBusinessCenterMeta.
export const SERP_TITLE_MAX_PX = 600;

export function serpTitleWidth(text: string, fontSizePx = 20): number {
  let units = 0;
  for (const char of text) units += WIDTHS.get(char) ?? FALLBACK_WIDTH;
  return (units * fontSizePx) / 1000;
}

export function fitsSerpTitle(text: string): boolean {
  return serpTitleWidth(text) <= SERP_TITLE_MAX_PX;
}
