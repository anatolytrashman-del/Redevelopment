// Ширина заголовка в выдаче Google считается в ПИКСЕЛЯХ, а не в символах:
// «Бизнес-центр Terrum — полный обзор» и «Бизнес-центры Минска: Октябрьский
// район» одинаково длинные в знаках, но вторая шире на четверть — у кириллицы
// «ш», «щ», «ю» втрое шире «i». Порог десктопной выдачи — около 600px при
// Arial 20px; что не влезло, показывается как «…полный обз…».
//
// Таблица ниже — реальные метрики Liberation Sans (метрически совместим с
// Arial, т.е. те же ширины глифов), в 1/1000 em, сгруппированные по значению.
// Считать ширину в браузере нельзя: заголовок собирается и при серверном
// пререндере, и в тестах, где никакого layout нет.
