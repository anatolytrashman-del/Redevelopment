// Раскладка блоков-рекомендаций («Бизнес-центры на этой улице», «Рейтинг БЦ»
// и т.п.) по странице бизнес-центра.
//
// Почему это отдельный модуль и третий заход (2026-09-21). Владелец:
// «блоки слишком сконцентрированы в середине сайта, часто попадают в один
// экран… нужна умная система, которая анализирует длину блоков, длину
// страницы и нативно вставляет блоки через каждые пару экранов. Их не
// должно быть мало, их не должно быть много.»
//
// Две предыдущие версии жили прямо в BusinessCenterDetailPage.tsx и обе
// ошибались одинаково — обе были ЖАДНЫМИ: шли сверху вниз и ставили
// очередной блок, как только с прошлого набралось сколько-то контента.
// У жадной раскладки два врождённых дефекта, и оба владелец и увидел:
//
//   1. Очередь кандидатов (их максимум 5) заканчивается в первой половине
//      страницы, а низ остаётся вообще без рекомендаций. Замер 2026-09-21
//      по 12 живым страницам (Chromium 1440×900, dev-сервер на боевых
//      данных): на ВСЕХ двенадцати последний блок стоял не ниже 58% высоты
//      страницы, а хвост в 3,5–5 экранов шёл без единой рекомендации
//      (victoria-plaza — 5 блоков, все в первых 58%; prizma — 3 блока в
//      первых 40%).
//   2. Порог считался в «экранах» по таблице SECTION_WEIGHTS, набранной на
//      глаз. Тот же замер: реальные высоты блоков оказались в 1,5–2 раза
//      меньше оценок (market 0,80 экрана против оценки 1,4; tenants 0,61
//      против 1,1; сам блок-рекомендация 0,30 против 0,6). Плюс после
//      установки блока счётчик стартовал не с нуля, а с веса самого блока,
//      так что «порог 1,0 экрана» на деле означал «0,4 экрана обычного
//      контента» — отсюда и соседние рекомендации в одном экране (siluet:
//      два блока через 474px друг от друга).
//
// Эта версия делает ровно то, что просил владелец, в два прохода:
// СНАЧАЛА измеряем всю страницу целиком (сколько блоков и какой длины),
// ПОТОМ раскладываем рекомендации равномерно по всей её длине. Сколько
// блоков поставить — считается из длины страницы, а не из того, сколько
// кандидатов нашлось.

// Раскладка одна на все ширины: она считается при рендере (в том числе при
// пререндере на сборке), а не по фактическому размеру окна — мерить высоты
// в браузере значило бы, что разметка пререндера и разметка после гидрации
// расходятся. Ширину это не ломает, потому что блоки расставляются по ДОЛЯМ
// страницы, а не по абсолютным экранам: замер того же «Порта» на 390×844
// даёт те же 18%/41%/73%, что и на десктопе, просто страница целиком
// растягивается с 9 экранов до 17.

/** Высота экрана, в которой измерены все веса ниже (десктоп 1440×900). */
const REFERENCE_VIEWPORT = 900;

const SCREEN = REFERENCE_VIEWPORT;

/**
 * Модель высоты блока: постоянная часть (заголовок, отступы, подпись
 * источника) плюс высота одного повторяющегося элемента списка/таблицы.
 *
 * Числа — не оценка на глаз, а линейная подгонка под замер 12 страниц
 * (см. шапку файла). Подгонка выходит почти точной, потому что почти всё
 * содержимое страницы — однотипные строки text-sm: у faq 45px на вопрос
 * (985px на 20 вопросов → 1390px на 29, то есть ровно 45 на каждый),
 * у market 66px на полосу сравнения, у media 43px на упоминание.
 *
 * `maxItems` — потолок для блоков с собственной пагинацией или свёрткой:
 * каталог арендаторов показывает 6 карточек из скольких угодно, и его
 * высота от числа организаций не зависит.
 */
interface SectionHeightModel {
  /** Постоянная часть блока, px при REFERENCE_VIEWPORT. */
  base: number;
  /** Высота одного элемента списка, px. */
  perItem: number;
  /** Сколько элементов блок реально показывает (пагинация/свёртка). */
  maxItems?: number;
}

const SECTION_HEIGHT_MODEL: Record<string, SectionHeightModel> = {
  // Строки таблицы предложений + плитка сравнения ставки (id
  // rate-comparison), которая рисуется вместе с ней и своего пункта меню
  // не имеет.
  offers: { base: 250, perItem: 45 },
  rental: { base: 190, perItem: 27 },
  tech: { base: 120, perItem: 42 },
  // Карта фиксированной высоты + чипы категорий инфраструктуры.
  map: { base: 450, perItem: 38 },
  // Пагинация по 6 организаций — высота одна и та же и на 8, и на 50.
  tenants: { base: 570, perItem: 0 },
  market: { base: 160, perItem: 70 },
  // База — бейджи рейтинга без единого отзыва (okean, 154px).
  reviews: { base: 155, perItem: 95, maxItems: 6 },
  awards: { base: 110, perItem: 40 },
  media: { base: 15, perItem: 80 },
  facts: { base: 145, perItem: 80 },
  history: { base: 0, perItem: 115 },
  developer: { base: 240, perItem: 15 },
  // <details>: в DOM есть и вопрос, и ответ, но на экране до раскрытия —
  // только строка вопроса.
  faq: { base: 85, perItem: 45 },
};

const DEFAULT_SECTION_MODEL: SectionHeightModel = { base: 300, perItem: 40 };

/** Отступ между блоками (`mt-6`). */
const SECTION_GAP = 24;

/** Шапка с фото, ценой и адресом — рисуется всегда, в pageSections её нет. */
const HERO_HEIGHT = 470;

/** Сам блок-рекомендация: две карточки БЦ + плитка каталога (замер: 272–284px). */
const RECOMMENDATION_HEIGHT = 275;

/**
 * Целевой интервал между соседними рекомендациями — «через каждые пару
 * экранов» (владелец, 2026-09-21). Именно он задаёт КОЛИЧЕСТВО блоков:
 * длинная страница получает больше, короткая — меньше.
 *
 * Считается по ОБЫЧНОМУ контенту, поэтому 1,75, а не 2: сам блок добавляет
 * ещё 0,3 экрана, и на глаз между соседними рекомендациями получается как
 * раз около двух экранов (замер после правки: 1,9–2,6).
 */
const TARGET_GAP = 1.75 * SCREEN;

/**
 * Жёсткий минимум между блоками. Меньше — и оба попадают в один экран
 * (ровно то, на что жаловался владелец), поэтому такой блок лучше не
 * ставить вовсе, чем ставить впритык.
 */
const MIN_GAP = 1.5 * SCREEN;

/**
 * Первая рекомендация — не раньше, чем после 3-го блока на экране
 * (владелец, 2026-09-20). Шапка страницы в список секций не входит,
 * поэтому по индексу это 2-й элемент списка, то есть индекс 1.
 */
const FIRST_ALLOWED_SECTION_INDEX = 1;

/**
 * Потолок на страницу — вторая половина требования «их не должно быть
 * мало, их не должно быть много». Кандидатов бывает и шесть (микрорайон,
 * метро, рейтинг, класс×район, улица, просто соседние), но шесть блоков
 * на одной странице — это уже каталог внутри карточки.
 */
const MAX_RECOMMENDATIONS = 5;

/** Блок страницы: идентификатор + сколько в нём повторяющихся элементов. */
export interface PageSectionSize {
  id: string;
  /** Строк таблицы, карточек, вопросов FAQ — смотря что за блок. */
  items: number;
}

/**
 * Сколько строк займёт текст в колонке шириной `charsPerLine` символов.
 * Нужен блокам, у которых число элементов постоянное, а высота — нет:
 * у «Условий для арендаторов» всегда ровно 4 строки-подписи, но текст под
 * ними различается в разы (245px у «Горецкого 14» против 811px у
 * «Проспекта»), и считать такой блок постоянным — та же ошибка, из-за
 * которой прошлые версии промахивались.
 */
export function estimateTextLines(text: string | null | undefined, charsPerLine: number): number {
  if (!text) return 0;
  return text
    .split('\n')
    .reduce((sum, line) => sum + Math.max(1, Math.ceil(line.trim().length / charsPerLine)), 0);
}

/** Оценка высоты блока в пикселях опорного экрана. */
export function estimateSectionHeight({ id, items }: PageSectionSize): number {
  const model = SECTION_HEIGHT_MODEL[id] ?? DEFAULT_SECTION_MODEL;
  const counted = Math.max(0, model.maxItems != null ? Math.min(items, model.maxItems) : items);
  return model.base + model.perItem * counted + SECTION_GAP;
}

/**
 * Раскладывает рекомендации по странице.
 *
 * @param sections блоки страницы в порядке вывода, ВКЛЮЧАЯ faq (его
 *   высоту надо знать, чтобы понимать длину хвоста, но сам он — граница:
 *   правило владельца «FAQ предпоследний, источники последние» означает,
 *   что ниже FAQ рекомендаций нет).
 * @param availableBlocks сколько блоков-кандидатов удалось собрать.
 * @returns id блоков, ПОСЛЕ которых встаёт рекомендация, сверху вниз.
 */
export function planRecommendationSlots(sections: PageSectionSize[], availableBlocks: number): string[] {
  if (availableBlocks <= 0) return [];

  // Шаг 1 — измеряем страницу целиком. Рекомендации ставятся только между
  // обычными блоками, но длину страницы считаем по всему содержимому,
  // включая FAQ и «Источники»: для читателя это такой же скролл.
  const anchors = sections.filter((s) => s.id !== 'faq');
  if (anchors.length === 0) return [];
  const heights = anchors.map(estimateSectionHeight);

  // Позиция границы ПОСЛЕ блока i — сколько страницы прокручено к этому
  // моменту. Считается без рекомендаций; добавленную ими высоту
  // учитываем ниже, при проверке фактического интервала.
  const boundary: number[] = [];
  let acc = HERO_HEIGHT + SECTION_GAP;
  for (const h of heights) {
    acc += h;
    boundary.push(acc);
  }

  const first = Math.min(FIRST_ALLOWED_SECTION_INDEX, anchors.length - 1);
  const last = anchors.length - 1;
  const spanStart = boundary[first];
  const spanEnd = boundary[last];
  const span = spanEnd - spanStart;

  // Шаг 2 — сколько блоков заслуживает эта страница. Считаем по длине
  // участка, на котором рекомендации вообще разрешены (от «после 3-го
  // блока» до «перед FAQ»), а не по числу найденных кандидатов: длинная
  // страница получает больше блоков, короткая — меньше. Крайние точки
  // участка входят в раскладку, поэтому на участок длиной span
  // укладывается span / TARGET_GAP интервалов, то есть на один блок больше.
  const desired = Math.max(1, Math.round(span / TARGET_GAP) + 1);
  const count = Math.min(desired, availableBlocks, MAX_RECOMMENDATIONS, anchors.length - first);
  if (count <= 0) return [];

  // Шаг 3 — раскладываем равномерно: цели стоят через одинаковые
  // промежутки от начала до конца разрешённого участка, так что первая и
  // последняя приходятся ровно на его края. Именно это и лечит главную
  // болезнь прошлых версий — блоки больше не могут закончиться в
  // середине страницы, последний всегда стоит перед FAQ.
  //
  // Единственный блок ставится не в начало участка, а в его середину:
  // одним он остаётся, когда кандидатов нашлось меньше, чем просит
  // длина страницы, и тогда честнее поделить страницу пополам, чем
  // отдать ему верх и бросить весь низ.
  const targets: number[] = [];
  if (count === 1) {
    targets.push(spanStart + span / 2);
  } else {
    for (let i = 0; i < count; i += 1) targets.push(spanStart + (span * i) / (count - 1));
  }

  const chosen: number[] = [];
  // Фактическая позиция границы: каждая уже поставленная выше
  // рекомендация сдвигает вниз всё, что под ней.
  const positionOf = (index: number, placedAbove: number) => boundary[index] + placedAbove * RECOMMENDATION_HEIGHT;
  const fits = (index: number) => {
    if (chosen.length === 0) return true;
    const prev = chosen[chosen.length - 1];
    if (index <= prev) return false;
    return positionOf(index, chosen.length) - positionOf(prev, chosen.length - 1) >= MIN_GAP;
  };

  for (let i = 0; i < count; i += 1) {
    let bestIndex = -1;
    let bestDistance = Number.POSITIVE_INFINITY;
    for (let index = first; index <= last; index += 1) {
      if (!fits(index)) continue;
      const distance = Math.abs(boundary[index] - targets[i]);
      if (distance < bestDistance) {
        bestDistance = distance;
        bestIndex = index;
      }
    }
    if (bestIndex >= 0) {
      chosen.push(bestIndex);
      continue;
    }
    // Место нашлось не для всех — обычный случай, когда блоки в хвосте
    // короткие и очередной встал бы впритык к предыдущему. Промежуточную
    // цель в этом случае просто пропускаем (блок впритык хуже, чем его
    // отсутствие), а вот ПОСЛЕДНЮЮ уступать нельзя: именно из-за этого
    // «Призма» в замере 2026-09-21 осталась с пустым хвостом в 5 экранов.
    // Поэтому последний блок сдвигает вниз предыдущий, а не отменяется.
    if (i < count - 1) continue;
    while (chosen.length > 0 && !fits(last)) chosen.pop();
    if (fits(last)) chosen.push(last);
  }

  const slots = chosen.map((index) => anchors[index].id);
  return slots;
}
