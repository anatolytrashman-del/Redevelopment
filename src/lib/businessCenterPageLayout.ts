const DEFAULT_SECTION_MODEL: SectionHeightModel = { base: 300, perItem: 40 };

/** Отступ между блоками (`mt-6`). */
const SECTION_GAP = 24;

/** Шапка с фото, ценой и адресом — рисуется всегда, в pageSections её нет. */
const HERO_HEIGHT = 470;

/** Сам блок-рекомендация: две карточки БЦ + плитка каталога (замер: 272–284px). */
const RECOMMENDATION_HEIGHT = 275;

/**
 * Целевой интервал между соседними рекомендациями — «через каждые пару
 * экранов» (владелец, 2026-09-21). Именно он задаёт КОЛИЧЕСТВО блоков:
 * длинная страница получает больше, короткая — меньше.
 *
 * Считается по ОБЫЧНОМУ контенту, поэтому 1,75, а не 2: сам блок добавляет
 * ещё 0,3 экрана, и на глаз между соседними рекомендациями получается как
 * раз около двух экранов (замер после правки: 1,9–2,6).
 */
const TARGET_GAP = 1.75 * SCREEN;

/**
 * Жёсткий минимум между блоками. Считается по тому, с какого расстояния
 * два блока перестают попадать в один экран: при высоте блока 275px это
 * 900 + 275 = 1175px, то есть 1,3 экрана. Остальное — запас на ошибку
 * оценки высот: прогон всех 141 страницы 2026-09-21 дал разброс до 0,17
 * экрана между планом и фактом, так что 1,55 в плане — это не меньше 1,38
 * на экране.
 *
 * Поднимать выше нельзя: тот же прогон с порогом 1,65 показал, чем это
 * кончается — там, где трёхблочная раскладка переставала проходить по
 * интервалу, страница откатывалась на два блока и получала дыру в 3,5–5
 * экранов. Слишком редкие блоки — больший грех, чем блоки в 1,4 экрана
 * друг от друга: во второй ситуации они всё равно не видны одновременно.
 */
const MIN_GAP = 1.55 * SCREEN;

/**
 * Первая рекомендация — не раньше, чем после 3-го блока на экране
 * (владелец, 2026-09-20). Шапка страницы в список секций не входит,
 * поэтому по индексу это 2-й элемент списка, то есть индекс 1.
 */
const FIRST_ALLOWED_SECTION_INDEX = 1;

/**
 * Потолок на страницу — вторая половина требования «их не должно быть
 * мало, их не должно быть много». Кандидатов бывает и шесть (микрорайон,
 * метро, рейтинг, класс×район, улица, просто соседние), но шесть блоков
 * на одной странице — это уже каталог внутри карточки.
 */
const MAX_RECOMMENDATIONS = 5;

/** Блок страницы: идентификатор + сколько в нём повторяющихся элементов. */
export interface PageSectionSize {
  id: string;
  /** Строк таблицы, карточек, вопросов FAQ — смотря что за блок. */
  items: number;
}

/**
 * Сколько строк займёт текст в колонке шириной `charsPerLine` символов.
 * Нужен блокам, у которых число элементов постоянное, а высота — нет:
 * у «Условий для арендаторов» всегда ровно 4 строки-подписи, но текст под
 * ними различается в разы (245px у «Горецкого 14» против 811px у
 * «Проспекта»), и считать такой блок постоянным — та же ошибка, из-за
 * которой прошлые версии промахивались.
 */
export function estimateTextLines(text: string | null | undefined, charsPerLine: number): number {
  if (!text) return 0;
  return text
    .split('\n')
    .reduce((sum, line) => sum + Math.max(1, Math.ceil(line.trim().length / charsPerLine)), 0);
}

/** Оценка высоты блока в пикселях опорного экрана. */
export function estimateSectionHeight({ id, items }: PageSectionSize): number {
  const model = SECTION_HEIGHT_MODEL[id] ?? DEFAULT_SECTION_MODEL;
  const counted = Math.max(0, model.maxItems != null ? Math.min(items, model.maxItems) : items);
  return model.base + model.perItem * counted + SECTION_GAP;
}

/**
 * Где встанут блоки — расстояние от верха страницы в «экранах», по той же
 * модели высот, которой пользуется раскладка. Нужна, чтобы проверять
 * интервалы, не пересчитывая веса второй раз на стороне вызывающего:
 * дублировать их — тот же класс ошибки, что и файлы-близнецы.
 */
export function recommendationPositions(sections: PageSectionSize[], slots: string[]): number[] {
  const anchors = sections.filter((s) => s.id !== 'faq');
  const positions: number[] = [];
  let offset = HERO_HEIGHT + SECTION_GAP;
  for (const section of anchors) {
    offset += estimateSectionHeight(section);
    if (slots.includes(section.id)) {
      positions.push((offset + positions.length * RECOMMENDATION_HEIGHT) / SCREEN);
    }
  }
  return positions;
}

/**
 * Раскладывает рекомендации по странице.
 *
 * @param sections блоки страницы в порядке вывода, ВКЛЮЧАЯ faq (его
 *   высоту надо знать, чтобы понимать длину хвоста, но сам он — граница:
 *   правило владельца «FAQ предпоследний, источники последние» означает,
 *   что ниже FAQ рекомендаций нет).
 * @param availableBlocks сколько блоков-кандидатов удалось собрать.
 * @returns id блоков, ПОСЛЕ которых встаёт рекомендация, сверху вниз.
 */
export function planRecommendationSlots(sections: PageSectionSize[], availableBlocks: number): string[] {
  if (availableBlocks <= 0) return [];

  // Шаг 1 — измеряем страницу целиком. Рекомендации ставятся только между
  // обычными блоками, но длину страницы считаем по всему содержимому,
  // включая FAQ и «Источники»: для читателя это такой же скролл.
  const anchors = sections.filter((s) => s.id !== 'faq');
  if (anchors.length === 0) return [];
  const heights = anchors.map(estimateSectionHeight);

  // Позиция границы ПОСЛЕ блока i — сколько страницы прокручено к этому
  // моменту. Считается без рекомендаций; добавленную ими высоту
  // учитываем ниже, при проверке фактического интервала.
  const boundary: number[] = [];
  let acc = HERO_HEIGHT + SECTION_GAP;
  for (const h of heights) {
    acc += h;
    boundary.push(acc);
  }

  const first = Math.min(FIRST_ALLOWED_SECTION_INDEX, anchors.length - 1);
  const last = anchors.length - 1;
  const spanStart = boundary[first];
  const spanEnd = boundary[last];
  const span = spanEnd - spanStart;

  // Шаг 2 — сколько блоков заслуживает эта страница. Считаем по длине
  // участка, на котором рекомендации вообще разрешены (от «после 3-го
  // блока» до «перед FAQ»), а не по числу найденных кандидатов: длинная
  // страница получает больше блоков, короткая — меньше. Крайние точки
  // участка входят в раскладку, поэтому на участок длиной span
  // укладывается span / TARGET_GAP интервалов, то есть на один блок больше.
  const desired = Math.max(1, Math.round(span / TARGET_GAP) + 1);
  const count = Math.min(desired, availableBlocks, MAX_RECOMMENDATIONS, anchors.length - first);
  if (count <= 0) return [];

  // Шаг 3 — раскладываем равномерно. Идеальные точки стоят через
  // одинаковые промежутки от начала до конца разрешённого участка, так
  // что первая и последняя приходятся ровно на его края. Именно это и
  // лечит главную болезнь прошлых версий — блоки больше не могут
  // закончиться в середине страницы, последний всегда стоит перед FAQ.
  //
  // Единственный блок ставится не в начало участка, а в его середину:
  // одним он остаётся, когда кандидатов нашлось меньше, чем просит
  // длина страницы, и тогда честнее поделить страницу пополам, чем
  // отдать ему верх и бросить весь низ.
  const targetsFor = (n: number) => {
    if (n === 1) return [spanStart + span / 2];
    return Array.from({ length: n }, (_, i) => spanStart + (span * i) / (n - 1));
  };

  // Фактическая позиция границы: каждая уже поставленная выше
  // рекомендация сдвигает вниз всё, что под ней.
  const positionOf = (index: number, placedAbove: number) => boundary[index] + placedAbove * RECOMMENDATION_HEIGHT;

  // Перебор, а не жадный проход сверху вниз. Границ на странице не больше
  // десятка, блоков — не больше пяти, так что вариантов сотни: посчитать
  // их все дешевле, чем городить правила выхода из тупика. А тупики у
  // жадного прохода были настоящие: на «Флагмане» он ставил второй блок
  // после каталога арендаторов, упирался в то, что до конца страницы
  // остаётся 2px меньше минимального интервала, и снимал уже
  // поставленный блок — страница теряла середину и оставалась с двумя
  // блоками там, где помещалось три (замер 2026-09-21).
  const bestArrangement = (n: number): number[] | null => {
    const targets = targetsFor(n);
    let best: number[] | null = null;
    let bestScore = Number.POSITIVE_INFINITY;
    const pick: number[] = [];
    const walk = (from: number, score: number) => {
      if (pick.length === n) {
        if (score < bestScore) {
          bestScore = score;
          best = [...pick];
        }
        return;
      }
      for (let index = from; index <= last; index += 1) {
        const depth = pick.length;
        if (depth > 0) {
          const prev = pick[depth - 1];
          if (positionOf(index, depth) - positionOf(prev, depth - 1) < MIN_GAP) continue;
        }
        const offset = boundary[index] - targets[depth];
        const next = score + offset * offset;
        // Счёт только растёт, поэтому ветка, уже проигравшая лучшей,
        // дальше не разворачивается.
        if (next >= bestScore) continue;
        pick.push(index);
        walk(index + 1, next);
        pick.pop();
      }
    };
    walk(first, 0);
    return best;
  };

  // Столько блоков, сколько просит длина страницы; если столько ровно не
  // раскладывается по минимальному интервалу — на один меньше.
  let chosen: number[] | null = null;
  for (let n = count; n >= 1 && chosen === null; n -= 1) chosen = bestArrangement(n);
  const slots = (chosen ?? []).map((index) => anchors[index].id);
  return slots;
}
