import { describe, expect, it } from 'vitest';
import { pageCuts, safeFileName, type PageBlock } from './htmlToPdf';

// Владелец, 2026-09-17: «выгрузка в pdf разрывает страницу на несколько,
// учти и адаптируй» — страница должна кончаться на границе строки таблицы,
// а не посреди неё и не внутри блока подписей.

// Подряд идущие куски одинаковой высоты: строки таблицы.
function rows(count: number, height: number, from = 0): PageBlock[] {
  return Array.from({ length: count }, (_, i) => ({ top: from + i * height, bottom: from + (i + 1) * height }));
}

describe('pageCuts', () => {
  it('короткий документ — одна страница', () => {
    expect(pageCuts(rows(5, 100), 500, 1000)).toEqual([500]);
  });

  it('режет по последней строке, которая помещается на страницу', () => {
    // Строки по 100, страница 350 — режем по 300, а не по 350 посреди строки.
    expect(pageCuts(rows(7, 100), 700, 350)).toEqual([300, 600, 700]);
  });

  it('не режет внутри неделимого блока — целиком переносит его на следующую страницу', () => {
    // Строки до 300 и блок подписей 300…420 со своей внутренней границей 360.
    const blocks: PageBlock[] = [
      ...rows(3, 100),
      { top: 300, bottom: 360 },
      { top: 360, bottom: 420 },
      { top: 300, bottom: 420 },
    ];
    // Страница 400: по линейке влезла бы внутренняя граница 360, но она
    // внутри блока 300…420 — значит режем по 300, а подписи уходят целиком.
    expect(pageCuts(blocks, 420, 400)).toEqual([300, 420]);
  });

  it('кусок выше страницы всё-таки режется по линейке, иначе документ не кончится', () => {
    expect(pageCuts([{ top: 0, bottom: 1000 }], 1000, 300)).toEqual([300, 600, 900, 1000]);
  });

  it('не вырождает страницу в полоску из-за слишком ранней границы', () => {
    expect(pageCuts([{ top: 0, bottom: 20 }, { top: 20, bottom: 600 }], 600, 300)).toEqual([300, 600]);
  });
});

describe('safeFileName', () => {
  it('убирает то, что ломает сохранение файла', () => {
    expect(safeFileName('Краски/обои: 90% <итог>')).toBe('Краски обои 90% итог');
  });

  it('пустое имя не оставляет файл без названия', () => {
    expect(safeFileName('///')).toBe('документ');
  });
});
