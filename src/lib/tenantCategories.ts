// Рубрики арендаторов из Яндекс.Карт → отрасли карточки БЦ.
//
// Зачем это вообще есть. У 2GIS отрасль организации приходит готовой: в
// `parent_id` первичной рубрики лежит одна из 28 «общих рубрик», их подписи —
// в `src/data/tenantIndustries.ts`. Яндекс такого поля не отдаёт: в срезе
// (`business_center_tenant_source_snapshots`, source `yandex_maps`) на
// организацию есть только текст рубрики, и разных значений там 2471. Чтобы
// диаграмма отраслей и сравнение с городом жили на яндексовской базе (решение
// владельца 2026-09-19, Б13 в docs/bc-catalog-redesign-plan.md), рубрику
// нужно свернуть в ту же шкалу из 28 отраслей — этим занимается файл.
//
// Почему карта именно здесь, в TS, а не в SQL: её читает фронт, а вторая копия
// в SQL-функции городского среза — ровно тот случай файлов-близнецов, от
// которого предостерегает CLAUDE.md (разошлись бы доли в диаграмме здания и
// доли «по каталогу», и заметить это было бы нечем). Поэтому SQL
// (`refresh_bc_tenant_city_categories()`) складывает городской срез по СЫРЫМ
// рубрикам, ничего про отрасли не зная, а сворачивает его в отрасли эта же
// карта на клиенте. Чистка рубрики детерминирована от строки, поэтому свернуть
// после агрегации — то же самое, что свернуть до неё.
import { TENANT_INDUSTRY_OTHER } from '../data/tenantIndustries';

// Хвост карточки Яндекса про место в здании («…, этаж 4», «подъезд 1»,
// «секция 3, помещение 22,») прилипает к рубрике, потому что парсер снимка
// режет текст карточки по стоп-словам (см. scripts/capture-yandex-bc-tenants.mjs).
// Здесь он срезается окончательно: с точки зрения отрасли «Крепёжные изделия»
// и «Крепёжные изделия подъезд 3» — одно и то же.
const PLACEMENT_WORDS = 'секция|сектор|помещение|подъезд|офис|этаж|вход|корпус|павильон|бутик|стенд';
// За словом места всегда идёт номер («подъезд 1», «офис 410,», «этаж -1») или
// название нежилого этажа («этаж цокольный»). Без этой проверки под нож
// попадала бы рубрика «Офис организации» — самая частая в срезе (871
// организация), а с ней и «Офис интернет-магазина», «Офис продаж».
const PLACEMENT_VALUE = '(?:-?\\d[^\\s,;]*|цокольный|подвальный|мансардный|антресольный)';
const PLACEMENT_TAIL_RE = new RegExp(`[\\s,]+(?:${PLACEMENT_WORDS})\\s+${PLACEMENT_VALUE}.*$`, 'iu');
// Конец русского слова — lookahead, а не \\b: граница слова в JS считается по
// ASCII, между «этаж» и пробелом её нет (CLAUDE.md, про кириллицу в регулярках).
const PLACEMENT_ONLY_RE = new RegExp(`^(?:${PLACEMENT_WORDS})\\s+${PLACEMENT_VALUE}`, 'iu');

/**
 * Рубрика в том виде, в каком её показываем и по какой группируем.
 * Возвращает null, если от рубрики после чистки ничего не осталось или в поле
 * лежало только место в здании («этаж 1», «этаж цокольный» — у таких карточек
 * Яндекс рубрику не указал вовсе).
 */
export function cleanTenantCategory(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const withoutPlacement = raw.replace(PLACEMENT_TAIL_RE, '');
  const trimmed = withoutPlacement.replace(/[\s,;·]+$/u, '').trim();
  if (!trimmed) return null;
  if (PLACEMENT_ONLY_RE.test(trimmed)) return null;
  return trimmed;
}

/**
 * Первая рубрика из перечисления — по ней определяется отрасль.
 * У Яндекса в поле может лежать несколько рубрик через запятую
 * («Ветеринарная клиника, ветеринарная лаборатория»), и первая из них —
 * основная, как и `rubrics[0]` у 2GIS.
 */
export function primaryTenantCategory(raw: string | null | undefined): string | null {
  const clean = cleanTenantCategory(raw);
  if (!clean) return null;
  const first = clean.split(',')[0].replace(/[\s;·]+$/u, '').trim();
  return first || null;
}

// Не организации, а оборудование и точки самообслуживания: банкоматы,
// кофейные автоматы, туалеты. Яндекс держит их в том же списке «Организации
// внутри», и без отсечки карточка врёт дважды — «организаций в здании» выше
// реального, а в отраслях появляется мусор. Пункты выдачи сюда сознательно НЕ
// входят: ПВЗ арендует помещение, это настоящий арендатор.
//
// Подпись всегда каноническая, а не как назвали точку в источнике: в одном
// «Метрополе» лежат «Кофейный автомат», «Кофейный автомат Альфа-Бизнес Хаб» и
// «Кофейный автомат, кофе с собой» — строка «в здании также есть» из таких
// имён читается как список опечаток, а не как список сервисов.
const AMENITY_LABELS: { re: RegExp; label: string }[] = [
  { re: /туалет/iu, label: 'Туалет' },
  { re: /банкомат/iu, label: 'Банкомат' },
  { re: /криптомат/iu, label: 'Криптомат' },
  { re: /кофейный автомат|кофемашина самообслуживания/iu, label: 'Кофейный автомат' },
  { re: /вендинг|вендомат|торговый автомат/iu, label: 'Вендинговый автомат' },
  { re: /платёжный терминал|платежный терминал|инфокиоск/iu, label: 'Платёжный терминал' },
  { re: /постамат/iu, label: 'Постамат' },
  { re: /аренда зарядных устройств|зарядная станция/iu, label: 'Зарядная станция' },
];

/** Каноническая подпись оборудования или null, если это настоящая организация. */
export function tenantAmenityLabel(raw: string | null | undefined, name?: string | null): string | null {
  const clean = cleanTenantCategory(raw) ?? '';
  for (const item of AMENITY_LABELS) {
    if (item.re.test(clean)) return item.label;
  }
  for (const item of AMENITY_LABELS) {
    if (item.re.test(name ?? '')) return item.label;
  }
  return null;
}

export function isTenantAmenity(raw: string | null | undefined, name?: string | null): boolean {
  return tenantAmenityLabel(raw, name) !== null;
}

// Карточка самого здания в списке его же организаций: «Порт» с рубрикой
// «Бизнес-центр», «Метрополь» с рубрикой «Торговый центр». Арендатором здание
// себе не является, а его рейтинг уже показан отдельным блоком выше.
const BUILDING_RUBRIC_RE =
  /^(бизнес[\s-]*центр|деловой центр|бизнес-парк|торгов(ый|о-развлекательный) центр|административное здание)(?![\p{L}])/iu;

export function isBuildingOwnCard(raw: string | null | undefined, nameMatchesBuilding: boolean): boolean {
  const clean = cleanTenantCategory(raw) ?? '';
  // Карточка без рубрики, но с названием самого здания — тоже здание, а не
  // арендатор. Живой случай: в срезе БЦ «V» лежат две организации с именем
  // «Столица» (второе название здания, см. alt_names) и пустой рубрикой.
  // Правило узкое сознательно — совпадения имени МАЛО, если рубрика есть:
  // одноимённая с домом компания на первом этаже бывает настоящим
  // арендатором.
  if (!clean) return nameMatchesBuilding;
  if (!BUILDING_RUBRIC_RE.test(clean)) return false;
  // Рубрика «Бизнес-центр» — это всегда само здание (то же правило уже стояло
  // в каталоге арендаторов и в миграции очистки, 2026-09-19). Для остальных
  // типов зданий («Торговый центр») требуем ещё и совпадения названия: ТЦ на
  // первом этаже БЦ — законный арендатор.
  return /^бизнес[\s-]*центр/iu.test(clean) || nameMatchesBuilding;
}

