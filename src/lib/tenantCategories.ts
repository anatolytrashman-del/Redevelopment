/**
 * Отрасль по рубрике Яндекса. Незнакомая рубрика честно уходит в «Другое» —
 * ровно так же, как незнакомый id общей рубрики у 2GIS (см. tenantIndustryLabel).
 */
export function tenantIndustryFromCategory(raw: string | null | undefined): string {
  const primary = primaryTenantCategory(raw);
  if (!primary) return TENANT_INDUSTRY_OTHER;
  for (const rule of INDUSTRY_RULES) {
    if (rule.re.test(primary)) return rule.industry;
  }
  // Вторая попытка по всей строке рубрик: у части организаций первая рубрика
  // общая («Оптовая компания»), а содержательная стоит второй.
  const clean = cleanTenantCategory(raw);
  if (clean && clean !== primary) {
    for (const rule of INDUSTRY_RULES) {
      if (rule.re.test(clean)) return rule.industry;
    }
  }
  return TENANT_INDUSTRY_OTHER;
}

export interface TenantPlacement {
  floor: string | null;
  office: string | null;
  entrance: string | null;
}

// Место в здании Яндекс кладёт не в отдельное поле, а в текст карточки:
// «…Открыто до среды Ветеринарная клиника этаж цокольный», «…Магазин одежды
// офис 401, этаж 4». Этаж есть у 57% организаций, офис/секция — у 31%; это то,
// чего нет в данных 2GIS вовсе, и ради чего база Яндекса взята основной.
const FLOOR_RE = /этаж\s+([^\s,;]+)/iu;
const OFFICE_RE = /(?:офис|помещение|кабинет)\s+([^\s,;]+)/iu;
const ENTRANCE_RE = /(?:подъезд|вход|секция|корпус)\s+([^\s,;]+)/iu;

export function parseTenantPlacement(rawText: string | null | undefined): TenantPlacement {
  const text = rawText ?? '';
  return {
    floor: text.match(FLOOR_RE)?.[1] ?? null,
    office: text.match(OFFICE_RE)?.[1] ?? null,
    entrance: text.match(ENTRANCE_RE)?.[1] ?? null,
  };
}

/** «этаж 4» / «цокольный этаж» — человеческая подпись из разобранного места. */
export function formatTenantPlacement(placement: TenantPlacement): string | null {
  const parts: string[] = [];
  if (placement.floor) parts.push(`${placement.floor} этаж`);
  if (placement.office) parts.push(`офис ${placement.office}`);
  if (placement.entrance) parts.push(`подъезд ${placement.entrance}`);
  return parts.length ? parts.join(', ') : null;
}
