// Как у агента считается статус (владелец, 2026-09-14: "сделай отсчёт онлайна
// от реальной функции, которая заявлена для агента"). До этого зелёный кружок
// "Онлайн" был нарисован константой и горел бы даже у намертво вставшего
// крона. Теперь карточка сравнивает время последней выполненной задачи (RPC
// ai_agents_last_activity) с тем, как часто заявленная функция обязана
// срабатывать, — см. getAiAgentStatus в lib/aiAgentsApi.ts.
export interface AiAgentHeartbeat {
  // Сколько минут молчания ещё считаются нормой. Отсчитывается от времени
  // последней задачи агента, то есть от реального следа его функции в базе.
  staleAfterMinutes: number;
  // true — функция ходит по расписанию (GitHub-крон, pg_cron), и молчание
  // дольше срока означает поломку ("Нет связи").
  // false — функция event-driven (письмо от поставщика, запрос владельца):
  // молчание означает просто отсутствие работы ("Ожидает задач"), поломкой
  // это называть нельзя.
  scheduled: boolean;
  // Человеческая расшифровка расписания для тултипа: "раз в час", "по запросу".
  cadence: string;
}

export interface AiAgent {
  id: string;
  name: string;
  // Аналог specialty у подрядчика — короткая подпись под именем.
  role: string;
  // Что агент делает; на карточке выводится списком.
  tasks: string[];
  // Аватар: общий значок робота или фирменный знак (ClaudeLogo).
  icon?: 'bot' | 'claude';
  // Короткий тег-бейдж справа от имени (владелец, 2026-09-14: «к имени
  // рядом добавь тег Max X20» — тариф подписки Claude, на котором работает
  // кодер).
  tag?: string;
  // Последняя задача, известная без похода в базу (у Claude Code это время
  // сборки прода). Если агента нет в ответе RPC ai_agents_last_activity —
  // карточка покажет это.
  staticActivity?: { label: string; doneAt: string };
  // Ожидаемый ритм заявленной функции — из него и считается статус.
  heartbeat: AiAgentHeartbeat;
}

