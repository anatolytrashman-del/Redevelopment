// Кварталы официального жилого справочника застройщика Минск Мира
// (владелец прислал полный список "дом → квартал", 2026-08-25) — используется
// для карты плотности бизнеса по кварталам (DistrictQuarterMap.tsx).
//
// polygons — МАССИВ подполигонов, не один полигон: у нескольких кварталов
// (владелец: "квартал" в названии дома не всегда один физический блок)
// здания из справочника лежат в 2-3 РАЗНЫХ местах района под одним именем —
// например "Мировые танцы" это Брилевская, 31/33/35 И ОТДЕЛЬНО, почти в
// 2 км, Игоря Лученка, 23/25/27. Первая версия рисовала это одним convex
// hull, который перечёркивал полкарты — заменено на несколько отдельных
// фигур одного цвета.
//
// Источники геометрии по кварталам (см. source у каждой записи ниже,
// удалён при сборке — держать в комментарии для будущих правок):
//  - yandex-envelope: официальная прямоугольная рамка квартала как отдельного
//    объекта в геокодере Яндекса (Эмиратс, Южная Америка) — подтверждена по
//    домам застройщика (>70% домов внутри рамки).
//  - yandex-real: точный полигон границы, вытащенный из card-страницы Яндекс
//    Карт (displayGeometry в JSON карточки объекта) — владелец прислал
//    webarchive именно такой страницы для куска "Мировые танцы" (Брилевская)
//    случайно (кликнул в карточку квартала, а не просто увидел в поиске) —
//    если он пришлёт так же остальные, эти approx заменить на точные.
//  - cluster-hull: ПРИБЛИЖЕНИЕ — здания квартала сгруппированы по близости
//    (порог 750 м между соседними домами), на каждую группу — convex hull;
//    группы у которых <3 дома — квадрат ~90x90м вокруг точки(-ек). НЕ идёт
//    по реальным дорогам, это временная замена до присылки владельцем
//    настоящих границ (просил кликать в карточку квартала перед сохранением
//    webarchive, не просто искать — тогда попадает displayGeometry).
export interface DistrictQuarter {
  id: string;
  label: string;
  numbers: number[];
  polygons: [number, number][][];
}

