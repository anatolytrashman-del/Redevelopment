// Позиция закупки — СНИМОК конкретного EstimateMaterial на момент создания
// закупки (владелец, 2026-08-27: список материалов "подгружается в смету"),
// не живая ссылка: если материал в смете потом поправят/удалят, уже
// созданная закупка не должна тихо разъехаться с тем, что реально заказали
// у поставщика. sourceMaterialId — id исходного EstimateMaterial, только
// для справки (не используется для пересчёта).
export interface PurchaseItem {
  id: string;
  sourceMaterialId: string | null;
  name: string;
  unit: string;
  quantity: number | null;
  price: number | null;
  note: string;
  // Владелец, 2026-09-04: "краска идёт в литрах, а поставщик выставляет
  // количество банок по Х литров... надо пересчитывать на литр, метр,
  // штуку, а не в целом" — price/quantity/unit выше остаются КАК В СЧЕТЕ
  // (правдиво показывают, что реально прислал поставщик — банки, не литры),
  // а unitPrice — цена за ОДНУ единицу измерения СМЕТНОГО материала (тот же
  // unit, что у EstimateMaterial), с которым сопоставлена эта позиция.
  // Заполняется только вручную при сопоставлении распознанного счёта с
  // позицией сметы (см. SupplierCorrespondenceTab.tsx) — опционально,
  // поэтому не ломает уже существующие места создания PurchaseItem по всему
  // проекту (закупки, ведомости, запросы Ресерча), которым это поле не
  // нужно. Используется только для сравнения "лучшая цена по позиции"
  // (bestPricesByMaterialId в Suppliers.tsx) — раньше туда попадал сырой
  // price со счёта без учёта того, что тара может быть другой.
  unitPrice?: number | null;
  // Позиции ведомости материалов (MaterialLedger.items) — снимок строки
  // сметы, снятый в момент добавления. Владелец, 2026-09-12: "внёс изменения
  // в ведомость материалов по керамограниту, а к новому письму прикрепляется
  // ведомость без изменений... при любом изменении ведомость должна
  // обновляться" — поэтому снимок больше не считается истиной: позиции с
  // sourceMaterialId зеркалятся из живой сметы на каждом рендере (см.
  // lib/ledgerSync.ts), а это поле перечисляет поля, которые пользователь
  // ОСОЗНАННО поправил руками прямо в ведомости (объём под конкретного
  // поставщика, своя формулировка параметров) — только они переживают
  // синхронизацию. Пусто/отсутствует = позиция целиком следует за сметой,
  // так что все ведомости, сохранённые до 2026-09-12, автоматически
  // подтягивают актуальные данные. К закупкам/счетам отношения не имеет.
  ledgerOverrides?: LedgerOverridableField[];
  // Вид соответствия позиции ведомости (см. PurchaseItemMatchKind ниже) и
  // пометка «чем отличается» («Мурал вместо Urban Home», «цены без НДС»).
  // Показываются в ячейке сравнения цен рядом с ценой — там, где принимают
  // решение. Заполняются вместе с sourceMaterialId/unitPrice в форме
  // сопоставления счёта; у строк без сопоставления смысла не имеют.
  matchKind?: PurchaseItemMatchKind;
  matchNote?: string;
  // Насколько модель уверена в привязке строки счёта к позиции ведомости,
  // 0…1 (шаг 5 плана закупок). Заполняется только автосопоставлением на
  // приёме письма (_invoiceApply.js); у строк, сопоставленных человеком, поля
  // нет — и это правильно: у человека нет «уверенности 0.8», он либо
  // сопоставил, либо нет. Отсутствие поля НЕ значит «не уверены»: в сравнении
  // цен помечается «проверить» только то, где уверенность реально низкая или
  // вид соответствия 'check'.
  matchConfidence?: number | null;
  // Владелец, 2026-09-15: «на все аналоги в идеале бы иметь ссылки. На сайте
  // поставщиков они часто есть, а зачастую и сами менеджеры в письме их
  // присылали» — ссылка на карточку товара (из письма менеджера или с сайта),
  // выводится под ценой в сравнении и в листе согласования.
  productUrl?: string;
  // Тара строки счёта (шаг 7 плана закупок): сколько и чего в ОДНОЙ единице
  // `unit` этой строки. «Краска Euro 7, 35 шт по 9 л» → unit 'шт',
  // quantity 35, packQty 9, packUnit 'л'. Заполняет распознавание, когда
  // объём тары виден в документе; раньше его выковыривали регулярным
  // выражением из названия прямо в момент подсказки (parsePackVolume), то
  // есть знание о таре нигде не хранилось и добывалось заново при каждом
  // открытии формы. Пусто — тары в строке нет (товар и так штучный) или её
  // не разглядели, тогда parsePackVolume по-прежнему пробует название.
  packQty?: number | null;
  packUnit?: string;
  // Включён ли НДС в `price` этой строки и по какой ставке (шаг 7 плана).
  // Относится к цене КАК В СЧЁТЕ; `unitPrice` при этом всегда с НДС — это
  // соглашение сравнения цен, и оно не менялось (см. форму сопоставления:
  // «за ед. сметы, с НДС»). Поле нужно, чтобы было видно, откуда взялась
  // цена за единицу: из документа напрямую или пересчётом из «без НДС».
  // null/отсутствует — счёт про НДС промолчал (и старые строки, записанные
  // до шага 7); это НЕ «без НДС», см. grossUp в data/vat.ts.
  vatIncluded?: boolean | null;
  vatRate?: number | null;
}

// Поля позиции ведомости, которые вообще можно поправить руками (в
// MaterialLedgerModal редактируются только они — название и единица всегда
// берутся из сметы).
export type LedgerOverridableField = 'quantity' | 'note';

// Владелец, 2026-09-15 (перестройка «Сравнения цен»): строка счёта
// поставщика, сопоставленная с позицией ведомости (sourceMaterialId), ещё
// не значит «ровно то, что просили». Реальный кейс керамогранита: из пяти
// поставщиков ровно по артикулам ответил один, остальные прислали аналоги
// (другая коллекция, другой бренд, чёрный вместо серого), а у двоих
// расхождение, которое надо уточнять (Dark Grey вместо Grey, толщина 20 мм
// вместо 9). По данным счёта это не отличить — вид ставит человек в форме
// сопоставления (SupplierCorrespondenceTab). 'delivery' — строка «Доставка
// за МКАД» и подобные: не материал, в таблице сравнения уходит в отдельную
// строку доставки, а не в позиции. Отсутствие поля (старые счета) = 'exact',
// если строка сопоставлена.
export type PurchaseItemMatchKind = 'exact' | 'alternative' | 'check' | 'delivery';

export const PURCHASE_ITEM_MATCH_KIND_LABELS: Record<PurchaseItemMatchKind, string> = {
  exact: 'ровно по ведомости',
  alternative: 'аналог',
  check: 'уточнить',
  delivery: 'доставка',
};

// Строка счёта похожа на доставку/транспорт — подсказка для формы
// сопоставления, окончательный вид всё равно выбирает человек.
export function looksLikeDeliveryItem(name: string): boolean {
  return /(доставк|транспорт|мкад|перевозк|delivery|логистик)/i.test(name);
}

export function purchaseItemTotal(item: PurchaseItem): number {
  return (item.quantity ?? 0) * (item.price ?? 0);
}

// Закупка — связывает поставщика (contractors, отфильтрованные так же, как
// вкладка "Каталог" на странице Suppliers.tsx — !teamTier, отдельного
// справочника поставщиков заводить не стали, он уже есть), раздел сметы
// (откуда взят список материалов) и переписку с поставщиком (см.
// data/purchaseEmails.ts). estimateId/sectionId — nullable: закупку можно
// начать до того, как выбрана смета/раздел.
export interface Purchase {
  id: string;
  title: string;
  status: string;
  contractorId: string | null;
  estimateId: string | null;
  sectionId: string | null;
  // Заголовок раздела на момент выбора — на случай переименования/удаления
  // раздела в смете после того, как закупка уже создана (см. EstimateSection —
  // разделы этой сметы уже переименовывались минимум дважды в этой же сессии).
  sectionTitle: string;
  items: PurchaseItem[];
  currency: Currency;
  // Короткий технический код для plus-адреса переписки (см.
  // purchaseEmailAddress ниже) — 5 hex-символов, генерируется в БД (default
  // на колонке short_code, миграция 2026-09-03), уникален.
  shortCode: string;
  createdAt: string;
}

// Форма строки в таблице Supabase (snake_case-колонки) — см. src/lib/purchasesApi.ts
export interface PurchaseRow {
  id: string;
  title: string;
  status: string;
  contractor_id: string | null;
  estimate_id: string | null;
  section_id: string | null;
  section_title: string | null;
  items: PurchaseItem[] | null;
  currency: string;
  short_code: string;
  created_at: string;
}

export function purchaseTotal(purchase: Pick<Purchase, 'items'>): number {
  return purchase.items.reduce((sum, item) => sum + purchaseItemTotal(item), 0);
}

