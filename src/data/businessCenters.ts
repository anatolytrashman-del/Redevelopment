  slug: string;
  name: string;
  address: string;
  // Административный район Минска (Центральный/Советский/Первомайский/...) —
  // владелец, 2026-09-04: "боковое меню... фильтр по районам". null — у
  // объектов физически вне Минска (см. "Аден" ниже), таких не показываем ни в
  // одном пункте фильтра по району, только в "Все районы".
