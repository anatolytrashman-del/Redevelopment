import type { Currency } from './transactions';

// Ручная корректировка "непогашенного остатка" для соло-плательщика вне
// пары (Татьяна Давыдчик, Влад Ждонец и т.п.) — владелец, 2026-08-31:
// "пометил все транзакции с Татьяной Давыдчик как зачтённые, но остался
// остаток — Татьяна Давыдчик должна мне $125, чтобы следующие транзакции
// шли в перезачёт с ней". Пометка "В расчете" на старых транзакциях снимает
// их из calculateSoloBalances (Transactions.tsx) насовсем — остаток от
// сверки, который они не покрывают, больше негде хранить, кроме отдельной
// записи. По одной строке на (плательщик, валюта) — новая корректировка
// того же плательщика/валюты просто заменяет предыдущую (см. upsert в
// transactionBalanceAdjustmentsApi.ts), это не журнал правок, а текущее
// значение остатка "с прошлого раза".
//
// Знак amount — как и у amount в calculateSoloBalances: положительное
// значение — компания должна плательщику, отрицательное — плательщик
// должен компании. Новые непогашенные траты того же плательщика
// автоматически прибавляются к этому остатку (в ту же сторону, что и
// раньше) — это и есть "перезачёт", ничего специально пересчитывать не
// нужно.
export interface TransactionBalanceAdjustment {
  id: string;
  payer: string;
  currency: Currency;
  amount: number;
  note: string;
  updatedAt: string;
}

export interface TransactionBalanceAdjustmentRow {
  id: string;
  payer: string;
  currency: string;
  amount: number;
  note: string | null;
  updated_at: string;
}
