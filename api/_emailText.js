// Отрезание процитированной переписки от ответа поставщика — общий хелпер
// для распознавания по ТЕКСТУ письма (шаг 10 плана закупок).
//
// Зачем это отдельная и довольно параноидальная функция. В ответе
// поставщика внизу лежит НАШЕ ЖЕ письмо: «Прикладываем ведомость
// материалов. Просьба прислать коммерческое предложение/счёт по позициям…»,
// а в переторжке — ещё и с ценами конкурентов. Если скормить модели письмо
// целиком, она прочитает наш запрос как предложение поставщика и запишет в
// карточку наши собственные позиции с нашими же числами. Для распознавания
// счёта во вложении это было неважно (числа брались из документа, письмо шло
// справочно и обрезалось до 800 символов), а для распознавания ПО ТЕКСТУ это
// главный источник мусора.
//
// Родственная функция splitQuotedReply живёт в
// src/components/suppliers/SupplierCorrespondenceTab.tsx — она прячет цитату
// под спойлер в интерфейсе. Это НЕ пара файлов-близнецов в смысле правила из
// CLAUDE.md: у интерфейса цена ошибки — свёрнутый лишний абзац, поэтому там
// эвристика мягкая (только ">" и «On … wrote:»); здесь цена ошибки — чужие
// числа в карточке поставщика, поэтому режем агрессивнее и по более широкому
// набору признаков. Общее у них одно: обе best-effort, формат цитирования
// почтового клиента отправителя заранее неизвестен.
//
// Набор признаков выведен из 125 живых входящих писем (выборка 2026-09-16):
// ">" — 56 писем, «писал(а):» — 33, блок заголовков «От:/From:» — 18,
// «Отправлено:/Sent:» — 10, «-----Original Message-----» — ни одного, но
// оставлено как самый распространённый в мире вариант Outlook на английской
// локали.

// Наши собственные адреса в шапке процитированного письма — самый надёжный
// признак: в тексте поставщика наш домен не встречается ни разу, а в цитате
// он есть почти всегда («От: "Redevelopment Закупки"
// <zakupki+9ee0e@redevelopment.pro>»).
const OUR_ADDRESS_RE = /[\w.+-]+@redevelopment\.pro/i;

// «---------- Пересланное сообщение ----------», «-----Original Message-----»
// и прочие разделители пересылки.
const SEPARATOR_RE = /^\s*[-_=]{2,}\s*(пересланное сообщение|исходное сообщение|original message|forwarded message|начало пересылаемого сообщения)/i;

// Преамбула ответа: «On Thu, 11 Sep 2026 … wrote:», «11.09.2026 … писал(а):»,
// «Вы писали 12 сентября 2026 г., 17:09:03:» (The Bat!/Mail.ru — глагол в
// начале строки, а двоеточие в конце принадлежит времени, поэтому проверять
// надо не хвост строки, а связку «глагол … двоеточие в конце»).
// (\b в JS — граница ASCII-слова, для кириллицы не работает вовсе: между
// «писали» и пробелом её нет. Поэтому конец слова проверяется явным
// lookahead по буквам с флагом u.)
const PREAMBLE_RE = /(wrote|schrieb|пишете|пишет|писали|писала|писал)(?![\p{L}]).{0,80}:\s*$/iu;

// Строка блока заголовков процитированного письма. Сама по себе основанием
// для реза НЕ является (поставщик может написать «Тема: счёт» в первой
// строке) — нужна пара таких строк подряд или наш адрес рядом, см. ниже.
const HEADER_LINE_RE = /^\s*(от|from|кому|to|cc|копия|отправлено|отправленные|отправил|sent|дата|date|тема|subject|reply-to)\s*:\s/i;

// Подпись отправителя: «-- » на отдельной строке (стандарт RFC 3676 §4.3)
// либо просто линейка из подчёркиваний/дефисов — так подпись отбивает
// половина русских почтовых клиентов. Режется отдельно от цитаты: в подписи
// менеджера лежат телефоны, адреса складов и ссылки — чисел там больше, чем
// в самом письме, и модель принимает «МКАД 2 км» и «8-800-70744-50» за
// данные поставки. Проверено на тех же 125 письмах: линейка есть в 43, и ни
// в одном из них в отрезаемом хвосте не осталось чисел, похожих на суммы.
const SIGNATURE_RE = /^\s*(--|[_\-=*~]{3,})\s*$/;

/**
 * Возвращает { text, cut } — текст без процитированной переписки и краткую
 * причину реза (для лога; null, если резать было нечего).
 */
export function stripQuotedReply(body) {
  const source = String(body ?? '')
    // Письмо приходит уже текстом (см. htmlToPlainText в _attachments.js),
    // но если в базе лежит старая запись с разметкой — не терять на ней
    // структуру строк.
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/(div|p|tr|li|h[1-6]|table)>/gi, '\n')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\r\n?/g, '\n');
  const lines = source.split('\n');

  let cutIndex = -1;
  let cut = null;
  for (let i = 0; i < lines.length; i++) {
    const trimmed = lines[i].trim();
    if (!trimmed) continue;
    if (trimmed.startsWith('>')) {
      cutIndex = i;
      cut = 'цитата ">"';
      break;
    }
    if (SEPARATOR_RE.test(trimmed)) {
      cutIndex = i;
      cut = 'разделитель пересылки';
      break;
    }
    if (PREAMBLE_RE.test(trimmed)) {
      cutIndex = i;
      cut = 'преамбула «… писал(а):»';
      break;
    }
    if (HEADER_LINE_RE.test(trimmed)) {
      // Одинокая строка «Тема: …» — не цитата. Цитатой считаем, только
      // если рядом (в пределах четырёх строк) есть вторая строка-заголовок
      // или наш собственный адрес.
      const near = lines.slice(i, i + 5).map((l) => l.trim());
      const headerCount = near.filter((l) => HEADER_LINE_RE.test(l)).length;
      if (headerCount >= 2 || near.some((l) => OUR_ADDRESS_RE.test(l))) {
        cutIndex = i;
        cut = 'шапка процитированного письма';
        break;
      }
    }
    if (OUR_ADDRESS_RE.test(trimmed)) {
      cutIndex = i;
      cut = 'наш адрес в цитате';
      break;
    }
  }

  let kept = cutIndex === -1 ? lines : lines.slice(0, cutIndex);

  // Преамбулу почтовый клиент часто переносит на несколько строк (Gmail
  // рвёт длинные строки), и тогда её хвост остался бы в видимой части —
  // отматываем границу назад через строки, похожие на фрагмент шапки.
  if (cutIndex !== -1) {
    let start = kept.length;
    for (let i = kept.length - 1; i >= 0; i--) {
      const trimmed = kept[i].trim();
      if (!trimmed) continue;
      if (HEADER_LINE_RE.test(trimmed) || PREAMBLE_RE.test(trimmed) || /^on\s/i.test(trimmed) || OUR_ADDRESS_RE.test(trimmed)) {
        start = i;
        continue;
      }
      break;
    }
    kept = kept.slice(0, start);
  }

  // Подпись отправителя отрезаем последней — уже от того, что осталось.
  const signatureIndex = kept.findIndex((l) => SIGNATURE_RE.test(l));
  if (signatureIndex !== -1) {
    kept = kept.slice(0, signatureIndex);
    if (!cut) cut = 'подпись';
  }

  const text = kept
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  return { text, cut };
}
