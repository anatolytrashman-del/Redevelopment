-- Пересборка публичных страниц — раз в час по накопленной отметке, а не на
-- каждое сохранение в админке (2026-09-19).
--
-- Зачем. api/trigger-rebuild.js дёргал Vercel Deploy Hook прямо из
-- сохранения объекта/бизнес-центра, с дебаунсом в 5 минут. Дебаунс
-- ограничивает частоту, но не общее число сборок за долгий сеанс правок:
-- непрерывная работа с карточками БЦ держала прод в режиме «каждые 5-6
-- минут новая сборка» больше часа. Один и тот же коммит ad16fdf собран в
-- прод пять раз подряд (18:25, 18:31, 18:36, 18:42, 18:48), каждая сборка
-- 6-7 минут, потому что scope business_centers означает полный рендер ~285
-- страниц. Владелец: «я не вношу новые правки и жду старые, а оно
-- продолжает грузить всё новые деплои» и «готов запускать перерендер
-- каждый час, если сможем хранить данные».
--
-- Как теперь. Сохранение в админке только ставит отметку в deploy_debounce
-- (triggered_at = сейчас, consumed_at = null, scope накапливается через
-- mergeScope). Этот крон раз в час смотрит, есть ли НЕПОТРЕБЛЁННАЯ отметка,
-- и только тогда дёргает Deploy Hook. Нет правок за час — нет и сборки,
-- пустых прогонов не будет. Правка, сделанная в любой момент часа, не
-- теряется: она лежит отметкой до ближайшей сборки, а scripts/prerender.mjs
-- забирает её атомарно (consumed_at) и делает настоящий рендер.
--
-- Минута выбрана так, чтобы не совпадать с соседями: поминутные воркеры
-- (:*), дожим поставщиков (:17), разбор почты (:27), Метрика (:37),
-- Вебмастер (05:47).
--
-- ВАЖНО: URL хука в репозиторий не кладём (POST на него запускает реальную
-- пересборку прода) — он лежит в Vault под именем vercel_deploy_hook_url.
-- Значение — то же самое, что в переменной окружения Vercel
-- VERCEL_DEPLOY_HOOK_URL (Vercel → Settings → Environment Variables).
-- ===========================================================================

-- Шаг 1. Один раз завести секрет, подставив значение из Vercel env:
-- select vault.create_secret(
--   '<значение VERCEL_DEPLOY_HOOK_URL из Vercel>',
--   'vercel_deploy_hook_url',
--   'Vercel Deploy Hook: почасовая пересборка публичных страниц'
-- );

-- Шаг 2. Само расписание.
select cron.schedule(
  'rebuild-public-pages',
  '13 * * * *',
  $cron$
  select net.http_post(
    url := (select decrypted_secret from vault.decrypted_secrets where name = 'vercel_deploy_hook_url'),
    headers := jsonb_build_object('Content-Type', 'application/json'),
    body := '{}'::jsonb,
    timeout_milliseconds := 5000
  )
  where exists (
    select 1 from deploy_debounce where id = 'default' and consumed_at is null
  );
  $cron$
);

notify pgrst, 'reload schema';
