-- Вторые названия здания (К20 плана каталога, 2026-09-20).
--
-- Замер Wordstat 18.08–18.09.2026: «бизнес центр столица минск» — 23
-- запроса в месяц плюс 9 у «…официальный сайт», вторая по частоте позиция
-- во всём топе «бизнес центр минск». Здания с таким именем у нас не было —
-- оказалось, что это наш же БЦ «V» на пр-те Победителей, 59: комплекс
-- «Виктория» управляется КУП «Бизнес-центр "Столица"», и людям здание
-- известно под обоими именами. Слово «Столица» на странице не встречалось
-- нигде, поэтому 32 запроса в месяц проходили мимо.
--
-- Отдельной записью заводить нельзя — это одно и то же здание, две
-- карточки на один адрес дали бы дубль. Поэтому массив вторых названий на
-- существующей строке: они идут в title, подпись под H1, description, FAQ
-- и alternateName разметки Place, и ими же отсеиваются карточки самого
-- здания из списка арендаторов (в яндексовском срезе БЦ «V» лежат две
-- организации с именем «Столица» и пустой рубрикой — это само здание).
alter table public.business_centers
  add column if not exists alt_names text[] not null default '{}';

comment on column public.business_centers.alt_names is
  'Другие названия здания, под которыми его ищут (БЦ «V» = «Столица»). Идут в title, H1-подпись, description, FAQ и alternateName разметки Place; ими же отсеиваются карточки самого здания из списка арендаторов.';

-- Имена поменяны местами по решению владельца в тот же день: «Столица» —
-- основное название (под «V» здание не ищут вовсе, в топ-23 Wordstat его
-- нет), «V» — второе. Слаг /minsk/bcminsk/v не менялся: переезд URL ради
-- косметики не стоит переиндексации. Описание переписано — прежний текст
-- утверждал, что отдельного здания под названием «Столица» нет, и после
-- переименования прямо противоречил заголовку страницы.
update public.business_centers
   set name = 'Бизнес-центр «Столица»',
       alt_names = array['V'],
       description = 'Офисные помещения в составе гостинично-делового комплекса «Виктория» на проспекте Победителей. Здание известно под двумя названиями: «Столица» — по управляющему КУП «Бизнес-центр "Столица"», и «V». Есть филиал с офисными и торговыми помещениями от 3,9 м² на пр-те Победителей, 103.'
 where slug = 'v';

notify pgrst, 'reload schema';
