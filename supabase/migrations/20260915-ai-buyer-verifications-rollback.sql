-- Откат 115 верификаций без почты с баланса ИИ-закупщика.
--
-- Владелец, 2026-09-15, следом за 20260915-verify-requires-email.sql (та
-- вернула в очередь 115 карточек на 112 доменов, верифицированных без email):
-- «вычти их из баланса ИИ-закупщика».
--
-- Как вычитаем: у 115 строк меняется action на
-- 'supplier_offer_verified_rolled_back'. Страница /admin/metrics считает
-- плитку «Верифицировано поставщиков» как ЧИСЛО СТРОК с action =
-- 'supplier_offer_verified' у профиля за период (aiBuyerStats в
-- pages/Metrics.tsx), поэтому переименование и есть вычитание — из 910
-- остаётся 795.
--
-- Почему не delete: сами события были — робот действительно пометил эти
-- карточки, по правилу, которое тогда стояло в базе. Стирать их значит
-- терять единственный след того, что произошло; переименование убирает их из
-- счётчика, но оставляет видимыми в /admin/activity-log под своей подписью
-- (ACTIVITY_ACTION_LABELS в data/activityLog.ts) и позволяет при нужде
-- посчитать масштаб той ошибки. Откатывается обратным update.
--
-- Почему не встречное событие «разверифицировал»: его пришлось бы датировать
-- сегодняшним днём — 14-е осталось бы завышенным, а сегодняшняя плитка ушла
-- бы в минус (разбивка на странице по дням).
--
-- Какие именно 115: все 910 записей ИИ-закупщика лежат одним днём
-- (2026-09-14) с profile_id = null и одинаковым action, то есть между собой
-- неразличимы — связи activity_log с карточкой нет по устройству таблицы
-- (см. data/activityLog.ts, сырое событие без ссылки на сущность). Берём 115
-- самых поздних.
--
-- Совместимо со старым кодом: колонки и функции не меняются, поле action —
-- свободный text, незнакомое значение старый фронт покажет как есть.

update activity_log
   set action = 'supplier_offer_verified_rolled_back'
 where id in (
   select id from activity_log
    where action = 'supplier_offer_verified'
      and profile_name = 'ИИ-закупщик'
    order by created_at desc, id desc
    limit 115
 );

