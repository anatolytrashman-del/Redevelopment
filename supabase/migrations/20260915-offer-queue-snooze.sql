-- Очередь верификации: пауза, а не подделка отметки.
--
-- Владелец, 2026-09-15: «полностью очисти очередь верификации, я пока не
-- буду ей заниматься, мне достаточно поставщиков». Пометить всех
-- верифицированными было бы враньём — verified с 14-го числа означает
-- «каталог распознан», его пересчитывает scripts/verify-recognized.mjs, и
-- следующий же прогон снял бы отметку обратно. Поэтому отдельное поле:
-- карточка цела, данные не тронуты, её просто не показывают в очереди.
--
-- Обратимо: «Вернуть в очередь» на вкладке верификации обнуляет поле у всех
-- разом. Совместимо со старым кодом (просто новая колонка, никто не обязан
-- её заполнять).
alter table supplier_research_offers
  add column if not exists queue_snoozed_at timestamptz;

comment on column supplier_research_offers.queue_snoozed_at is
  'Когда карточку убрали из очереди верификации «на потом». NULL — в очереди на общих основаниях.';

notify pgrst, 'reload schema';
