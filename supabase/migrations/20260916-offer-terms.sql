-- Условия поставки, названные в письме БЕЗ счёта (шаг 6b плана
-- docs/procurement-product-steps.md).
--
-- Шаг 6a научил распознавание вытаскивать срок, доставку и предоплату из
-- счёта вместе с текстом письма, и кладёт их в supplier_offer_quotes.terms —
-- то есть условия конкретного предложения. Но половина переписки идёт без
-- вложений вовсе: «есть на складе, отгрузим за 5 дней, доставка бесплатно от
-- 300 000» — и таких условий до сих пор не оставалось нигде, кроме глаз
-- закупщика.
--
-- Это НЕ условия конкретного КП, поэтому и колонка другая: здесь «последнее,
-- что поставщик сказал про условия в этой категории». В сравнении цен они
-- показываются, когда у самого КП условий нет.
alter table supplier_research_offers add column if not exists terms jsonb;

comment on column supplier_research_offers.terms is
  'Последние условия, названные поставщиком в переписке без счёта. У конкретного КП свои условия в supplier_offer_quotes.terms — они важнее.';

notify pgrst, 'reload schema';
