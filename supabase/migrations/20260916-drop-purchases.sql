-- Шаг 11b плана закупок (docs/procurement-product-steps.md): снос мёртвой
-- сущности Purchase из первого прототипа.
--
-- Что это было: закупка, которую заводили руками, поставщиком в ней был
-- подрядчик из «Команды», с отбором цен она связана не была. Её заменил
-- заказ поставщику (purchase_orders), который рождается из утверждённого
-- листа сравнения — позиции, цены и поставщик берутся из того, что уже
-- утвердил руководитель.
--
-- Почему это безопасно: перед сносом проверено запросом — в обеих таблицах
-- НОЛЬ строк (16.09.2026), на них не ссылается ни один внешний ключ извне
-- (единственный FK — purchase_emails → purchases, уходит вместе с ними), ни
-- одна функция и ни одно представление. Плюс-адрес zakupki+<код>@ в
-- purchase_emails не маршрутизируется: код резолвится по short_code, а
-- строк, в которых он мог бы найтись, нет.
--
-- Порядок относительно кода: сначала выкачен код без обращений к этим
-- таблицам (PR со ссылкой на шаг 11b), READY дождались, и только потом эта
-- миграция — правило «добавить можно сразу, удалить только после READY».

drop table if exists purchase_emails;
drop table if exists purchases;

notify pgrst, 'reload schema';
