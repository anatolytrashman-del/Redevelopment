-- Ежемесячная принудительная пересборка публичных страниц.
--
-- Зачем. С 2026-09-22 сниппет каждой публичной страницы каталога обещает
-- две вещи: «полный обзор <год>» в заголовке и «Обновляется ежемесячно» в
-- описании (формат задан владельцем, см. fallbackBusinessCenterMeta в
-- src/lib/pageMeta.ts). Обе строки собираются в момент РЕНДЕРА, а пререндер
-- с 2026-09-19 запускается только когда есть отметка в deploy_debounce —
-- то есть когда менялся код публичных страниц или сохраняли БЦ в админке.
-- Спокойный месяц без правок означал бы, что в выдаче висит прошлогодний
-- год и обещание обновления, которого не было: сниппет, обещающий свежесть
-- и не подтверждающий её, хуже прежнего скучного.
--
-- Как. Отдельного механизма не заводим — ставим ровно ту же отметку, что
-- ставит сохранение бизнес-центра в админке (api/trigger-rebuild.js,
-- scope = 'business_centers' → полный пререндер всех ~286 путей, см.
-- scripts/prerender.mjs). Забирает её тот же почасовой rebuild-public-pages
-- в 13 минут, атомарно, поэтому гонки с ручным сохранением тут нет: если
-- владелец в ту же ночь что-то правил, отметка просто сольётся в одну.
--
-- Расписание: 1-го числа в 02:40 UTC (05:40 по Минску) — ночь, никто не
-- работает в админке, и до утра успевает достроиться даже полный рендер
-- (~6 минут). consumed_at сбрасывается в null ЯВНО, как и в
-- api/trigger-rebuild.js: без этого уже потреблённая отметка осталась бы
-- «обработанной» и сборка не пошла бы.
select cron.schedule(
  'monthly-prerender-refresh',
  '40 2 1 * *',
  $cron$
  insert into deploy_debounce (id, triggered_at, consumed_at, scope)
  values ('default', now(), null, 'business_centers')
  on conflict (id) do update
    set triggered_at = excluded.triggered_at,
        consumed_at = null,
        scope = 'business_centers';
  $cron$
);

notify pgrst, 'reload schema';
