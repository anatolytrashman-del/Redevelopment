-- Отметка тем, у кого почта есть, а формальной пары «снимок меню + снятый
-- контакт» нет.
--
-- Владелец, 2026-09-15 (после прогона робота по доборе почты): «что
-- распознали, добавляй в базу. Что нет, хрен с ним».
--
-- Кого это касается: 8 доменов (vseinstrumenti.ru, glassway.group,
-- leonito.ru, kraskideco.ru, lotokdkc.ru, p-z-m.ru, velegurin.ru и один
-- белорусский). Адрес у них в карточке есть — пришёл веб-поиском или руками,
-- — но verify_supplier_offers_with_captures их не берёт: она требует строку
-- и в supplier_menu_captures, и в supplier_contact_captures, а у этих есть
-- только одно из двух (glassway.group и leonito.ru сидят за антиботом с
-- 14.09, robot до их контактов не дошёл). Кнопка «Верифицировать» на
-- карточке требует ровно одно — непустой email, то есть руками владелец
-- пометил бы их той же кнопкой; это её массовый эквивалент.
--
-- Саму функцию НЕ ослабляем: её пара «меню + контакт» — это признак «робот
-- реально открывал сайт», и для автоматического пути он нужен. Здесь
-- разовое решение владельца по конкретному остатку, а не новое правило.
--
-- Логируем на ИИ-закупщика, как все прочие автоматические отметки (владелец,
-- 2026-09-14: «все верифицированные автоматическим образом поставщики на
-- странице метрики идут на баланс ИИ-закупщика»).
with up as (
  update supplier_research_offers o
     set verified = true
   where coalesce(o.verified, false) = false
     and coalesce(trim(o.email), '') <> ''
  returning o.id
)
insert into activity_log (profile_id, profile_name, action)
select null, 'ИИ-закупщик', 'supplier_offer_verified' from up;

-- Остаток — те, у кого почты нет нигде: 27 российских сайтов, которые её не
-- публикуют (робот брал контакты дважды, там только телефоны и мессенджеры),
-- 8 белорусских (половина вообще не открылась) и хвост отложенных. Для них
-- работы не осталось: кнопка без email выключена, робот их уже прошёл. Чтобы
-- вкладка не звала в очередь, где ничего нельзя нажать (ровно та поломка, из-за
-- которой сегодня чинили очередь), убираем их тем же механизмом, что владелец
-- применил 15.09, — queue_snoozed_at. Данные целы, возврат — кнопкой «Вернуть
-- в очередь» на вкладке.
update supplier_research_offers
   set queue_snoozed_at = now()
 where coalesce(verified, false) = false
   and queue_snoozed_at is null;

notify pgrst, 'reload schema';
