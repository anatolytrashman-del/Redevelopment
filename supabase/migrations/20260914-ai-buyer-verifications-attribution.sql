-- Метрики: ИИ-закупщик как отдельный "сотрудник" (владелец, 2026-09-14: "я
-- настроил автоматические ответы на письма поставщиков. Добавь на страницу
-- метрики юзера ИИ-закупщик, трекай автоматические ответы и все сегодняшние
-- верификации поставщиков под его юзернеймом").
--
-- Новых таблиц/колонок не нужно: автоответы уже подписываются
-- sent_by_name = 'ИИ-закупщик' в самой функции auto_reply_apply (см.
-- 20260914-email-auto-reply*.sql и docs/auto-reply-routine.md), а страница
-- /admin/metrics считает по profile_name / sent_by_name. Единственное, что
-- переносится в данных — верификации поставщиков за 14 сентября 2026 (по
-- Москве): они были записаны под профилем владельца ("Трэшмен"), владелец
-- попросил учитывать их за ИИ-закупщиком. profile_id обнуляется — у
-- ИИ-закупщика нет строки в access_profiles, и приписывать его действия
-- uuid владельца было бы той же ошибкой, что и имя.
--
-- Только UPDATE данных, схема не меняется; старый код на проде продолжает
-- работать (profile_name — свободный text, profile_id nullable).

update public.activity_log
   set profile_name = 'ИИ-закупщик',
       profile_id = null
 where action = 'supplier_offer_verified'
   and profile_name = 'Трэшмен'
   and created_at >= (date '2026-09-14'::timestamp at time zone 'Europe/Moscow')
   and created_at <  (date '2026-09-15'::timestamp at time zone 'Europe/Moscow');
